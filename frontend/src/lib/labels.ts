/** Friendly labels for the backend's voluntary self-ID option codes (backend/app/api/account_extra.py).
    Pass the `t` from useT(); unknown codes fall back to a readable form of the code. */
import type { MessageKey, TFunction } from "./i18n";

const GENDER_KEY: Record<string, MessageKey> = {
  woman: "labels.gender.woman",
  man: "labels.gender.man",
  non_binary: "labels.gender.non_binary",
  self_describe: "labels.gender.self_describe",
  prefer_not: "labels.gender.prefer_not",
};

const AGE_BAND_KEY: Record<string, MessageKey> = {
  under_25: "labels.age.under_25",
  "55_plus": "labels.age.55_plus",
  prefer_not: "labels.age.prefer_not",
};
/** Numeric ranges read the same in every language. */
const AGE_BAND_RANGE: Record<string, string> = { "25_34": "25–34", "35_44": "35–44", "45_54": "45–54" };

const DIMENSION_KEY: Record<string, MessageKey> = { gender: "labels.dim.gender", age_band: "labels.dim.age_band" };

export function genderLabel(t: TFunction, code: string) {
  return GENDER_KEY[code] ? t(GENDER_KEY[code]) : code.replace(/_/g, " ");
}

export function ageBandLabel(t: TFunction, code: string) {
  return AGE_BAND_KEY[code] ? t(AGE_BAND_KEY[code]) : (AGE_BAND_RANGE[code] ?? code.replace(/_/g, " "));
}

export function dimensionLabel(t: TFunction, dim: string) {
  return DIMENSION_KEY[dim] ? t(DIMENSION_KEY[dim]) : dim.replace(/_/g, " ");
}

export function groupLabel(t: TFunction, dim: string, g: string) {
  return dim === "gender" ? genderLabel(t, g) : dim === "age_band" ? ageBandLabel(t, g) : g.replace(/_/g, " ");
}

/* ---------------------------------------------------------------- analysis vocabulary
   The API sends role titles, seniority bands and rubric category names in English but also a stable id;
   these translate by id and fall back to the API's English text for ids the interface doesn't know yet
   (e.g. a role added to the taxonomy later). Free text generated by the backend (reasons, findings, tips)
   is not translated. */
const ROLE_IDS = [
  "ml_engineer", "data_scientist", "data_analyst", "data_engineer", "backend_developer", "frontend_developer",
  "fullstack_developer", "mlops_engineer", "devops_engineer", "qa_automation_engineer", "nlp_llm_engineer", "mobile_developer",
] as const;
const SENIORITY_IDS = ["entry", "junior", "mid", "senior", "staff"] as const;
const CATEGORY_IDS = ["completeness", "bullet_quality", "quantification", "action_verbs", "clarity", "skill_evidence", "dates", "parsing"] as const;

function has<T extends string>(list: readonly T[], v: string | null | undefined): v is T {
  return !!v && (list as readonly string[]).includes(v);
}

/** Translated role title by taxonomy id; `fallback` is the API's English title. */
export function roleTitle(t: TFunction, id: string | null | undefined, fallback?: string | null): string {
  if (has(ROLE_IDS, id)) return t(`role.${id}`);
  return fallback ?? (id ? id.replace(/_/g, " ") : "");
}

/** Whether roleTitle() would show a translation (so callers can drop lang="en" on the element). */
export function isKnownRole(id: string | null | undefined) {
  return has(ROLE_IDS, id);
}

export function seniorityLabel(t: TFunction, id: string | null | undefined, fallback?: string | null): string {
  if (has(SENIORITY_IDS, id)) return t(`seniority.${id}`);
  return fallback ?? id ?? "";
}

/** Rubric category name by id (analysis categories, version comparison). */
export function categoryName(t: TFunction, id: string | null | undefined, fallback?: string | null): string {
  if (has(CATEGORY_IDS, id)) return t(`rubric.cat.${id}`);
  return fallback ?? id ?? "";
}

export function effortLabel(t: TFunction, effort: string): string {
  return effort === "low" || effort === "medium" || effort === "high" ? t(`effort.${effort}`) : effort;
}

/* ---------------------------------------------------------------- resume titles
   A resume uploaded without a title is named after its file ("p02", "Resume_final_v3"). File-name codes
   say nothing about the resume, so show "Untitled resume" instead; readable file names are tidied up
   ("Jane_Doe_Resume" -> "Jane Doe Resume"). Titles the user typed are shown as they are. */
const GENERIC_NAME = /^(?:[a-z]{0,3}[-_ ]?\d+|resume|cv|curriculum vitae|document|doc|file|scan|untitled|new|final|draft|copy)(?:[-_ ]?(?:resume|cv|final|draft|copy|new|v?\d+))*$/i;

export function resumeTitle(t: TFunction, r: { title: string; original_filename?: string | null }): string {
  const title = (r.title ?? "").trim();
  const stem = (r.original_filename ?? "").replace(/\.[^.]+$/, "").trim();
  const fromFile = !!stem && title === stem;
  if (!title || (fromFile && GENERIC_NAME.test(title))) return t("dash.untitled");
  if (fromFile) {
    const tidy = title.replace(/[_]+/g, " ").replace(/\s+/g, " ").trim();
    return tidy.length >= 3 && /[a-z]{3}/i.test(tidy) ? tidy : t("dash.untitled");
  }
  return title;
}

/** lang attribute for a displayed resume title: titles come from the resume (read in English) or from the
    file name, so they are marked English unless the interface shows its own "Untitled resume". */
export function resumeTitleLang(t: TFunction, r: { title: string; original_filename?: string | null }): "en" | undefined {
  return resumeTitle(t, r) === t("dash.untitled") ? undefined : "en";
}

/* ---------------------------------------------------------------- sessions
   The account's session list stores the raw browser identification string. Show "Chrome on Windows"
   instead; anything unrecognised becomes "Unknown browser" / "Unknown device". */
export function deviceLabel(t: TFunction, ua: string | null | undefined): string {
  if (!ua) return t("settings.unknownDevice");
  const browser = /Edg\//.test(ua)
    ? "Edge"
    : /OPR\/|Opera/.test(ua)
      ? "Opera"
      : /SamsungBrowser/.test(ua)
        ? "Samsung Internet"
        : /Firefox\/|FxiOS/.test(ua)
          ? "Firefox"
          : /Chrome\/|CriOS/.test(ua)
            ? "Chrome"
            : /Safari\//.test(ua)
              ? "Safari"
              : null;
  const os = /Windows/.test(ua)
    ? "Windows"
    : /iPhone|iPad|iPod/.test(ua)
      ? "iOS"
      : /Android/.test(ua)
        ? "Android"
        : /Mac OS X|Macintosh/.test(ua)
          ? "macOS"
          : /CrOS/.test(ua)
            ? "ChromeOS"
            : /Linux/.test(ua)
              ? "Linux"
              : null;
  if (/HeadlessChrome|python-requests|curl\/|httpx|node-fetch|Go-http-client/i.test(ua)) return t("settings.automatedClient");
  if (browser && os) return t("settings.browserOn", { browser, os });
  if (browser) return browser;
  if (os) return t("settings.unknownBrowserOn", { os });
  return t("settings.unknownDevice");
}

/* ---------------------------------------------------------------- file problems
   Upload rejections (422 at upload) and processing failures (a FAILED job with error_code: encrypted,
   too many pages, damaged…) and bulk-upload per-file failures carry a stable code. Show our own translated
   explanation for known codes and the API's English message otherwise. */
const FILE_ERRORS = [
  "encrypted_pdf", "encrypted_docx", "too_many_pages", "corrupted_pdf", "corrupted_docx", "empty_text", "empty_file",
  "scanned_pdf", "ocr_unavailable", "parse_timeout", "parser_crashed", "worker_lost", "time_budget_exceeded",
  "bad_signature", "mime_mismatch", "unsupported_type", "macro_document", "docx_too_complex", "file_missing",
] as const;

/** Problems with the file itself: retrying the same file cannot help, a different file is needed. */
const PERMANENT_FILE_ERRORS = new Set<string>([
  "encrypted_pdf", "encrypted_docx", "too_many_pages", "corrupted_pdf", "corrupted_docx", "empty_text", "empty_file",
  "scanned_pdf", "bad_signature", "mime_mismatch", "unsupported_type", "macro_document", "docx_too_complex",
]);

export function fileErrorMessage(t: TFunction, code: string | null | undefined, fallback?: string | null): string {
  if (has(FILE_ERRORS, code)) return t(`fileErr.${code}`);
  return fallback || t("fileErr.generic");
}

export function isPermanentFileError(code: string | null | undefined): boolean {
  return !!code && PERMANENT_FILE_ERRORS.has(code);
}
