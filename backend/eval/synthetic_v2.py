    # label years from the dates actually written, counting months inclusively (Jan–Mar = 3 months)
    now = _months(AS_OF)
    years = sum((now if e["current"] else _months(e["end"])) - _months(e["start"]) + 1 for e in exp) / 12
    edu_end = int(exp[-1]["start"][:4])
    degree = rng.choice(["B.Tech in Computer Science", "B.Sc. in Statistics", "B.E. in Information Technology", "M.Sc. in Data Science",
                         "B.Com", "B.Sc. Nursing", "B.Des in Communication Design", "B.E. in Mechanical Engineering", "B.Ed"])
