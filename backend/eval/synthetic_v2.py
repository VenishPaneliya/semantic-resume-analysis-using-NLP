def _fmt(ym: str | None, style: str, current: bool = False) -> str:
    if current:
        return "Present"
    if not ym:
        return ""
    y, m = ym.split("-") if "-" in ym else (ym, None)
    if style == "MM/YYYY" and m:
        return f"{m}/{y}"
    if style == "YYYY" or not m:
        return y
    return f"{MON[int(m) - 1]} {y}"


def render_text(c: dict, lay: dict) -> str:
    h, bul = lay["h"], lay["bul"] or "•"
    ct = c["contact"]
    out = [ct["name"], " | ".join(x for x in [ct.get("location"), ct.get("email"), ct.get("phone")] if x), ""]
    if c.get("summary"):
        out += [h["sum"], c["summary"], ""]
    out.append(h["exp"])
    for e in c["experience"]:
        dates = f"{_fmt(e['start'], lay['date'])} – {_fmt(e.get('end'), lay['date'], e.get('current', False))}"
        if lay["tl"] == "org—title(dates)":
            out.append(f"{e['organization']} — {e['title']} ({dates})")
        elif lay["tl"] == "title, org":
            out += [f"{e['title']}, {e['organization']}", dates]
        elif lay["tl"] == "title at org":
            out += [f"{e['title']} at {e['organization']}", dates]
        else:
            out += [f"{e['title']} | {e['organization']}", dates]
        out += [f"{bul} {b}" for b in e["bullets"]]
    out.append("")
    out.append(h["edu"])
    for ed in c["education"]:
        out.append(f"{ed['degree']}, {ed['institution']}, {ed['start']} – {ed['end']}")
    out.append("")
    sk = c["skills"]["technical"] + c["skills"]["soft"]
    if sk:
        out.append(h["sk"])
        if lay["sk"] == "pipe":
            out.append(" | ".join(sk))
        elif lay["sk"] == "lines":
            out += [f"{bul} {s}" for s in sk]
        else:
            out.append(", ".join(sk))
    return "\n".join(out).strip() + "\n"


def to_docx(c: dict, lay: dict) -> bytes:
    from docx import Document

    doc = Document()
    for line in render_text(c, {**lay, "bul": "•"}).split("\n"):
        if line in lay["h"].values():
            doc.add_heading(line, level=1)
        elif line.startswith("• "):
            doc.add_paragraph(line[2:], style="List Bullet")
        elif line:
            doc.add_paragraph(line)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def render(persona: dict, layout: str) -> tuple[str, bytes]:
    from eval.synthetic import text_to_pdf

    lay = LAYOUTS[layout]
    if lay["kind"] == "docx":
        return "docx", to_docx(persona["content"], lay)
    return "pdf", text_to_pdf(render_text(persona["content"], lay))


