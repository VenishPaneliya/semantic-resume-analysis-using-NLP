JD_STYLES = ("bulleted", "inline", "prose")


def make_jd(jid: str, role: str, rng: random.Random, style: str) -> dict:
    spec = P[role]
    req = rng.sample(spec["core"], k=min(4, len(spec["core"])))
    pref = rng.sample([s for s in spec["opt"]], k=min(3, len(spec["opt"])))
    years = rng.choice([1, 2, 3, 5])
    title = spec["titles"][0]
    f = {s: rng.choice(FORMS[s]) for s in req + pref}
    if style == "bulleted":
        text = (f"Job Title: {title}\nCompany: {rng.choice(ORGS)}\n\nAbout the role\nYou will join the {rng.choice(TEAMS)} team.\n\n"
                "Responsibilities\n- Own features end to end\n- Work with product and design\n\nRequirements\n"
                + "".join(f"- Experience with {f[s]}\n" for s in req)
                + f"- {years}+ years of professional experience\n- Bachelor's degree in a related field\n\nNice to have\n"
                + "".join(f"- {f[s]}\n" for s in pref))
    elif style == "inline":
        text = (f"{title}\n\nWe are hiring a {title.lower()} for our {rng.choice(TEAMS)} team.\n"
                f"Requirements: {', '.join(f[s] for s in req)}.\nNice to have: {', '.join(f[s] for s in pref)}.\n"
                f"Experience: {years}+ years.\n")
        text = text.replace(f"Experience: {years}+ years.", f"At least {years}+ years of industry experience.")
    else:
        text = (f"{title}\n\nOur {rng.choice(TEAMS)} team is looking for someone who is comfortable with "
                f"{', '.join(f[s] for s in req[:-1])} and {f[req[-1]]}. You should have {years}+ years of professional experience. "
                f"It is a plus if you have worked with {' or '.join(f[s] for s in pref)}.\n")
    return {"id": jid, "role": role, "style": style, "text": text,
            "labels": {"required_skills": sorted(req), "preferred_skills": sorted(pref), "years_min": years, "title": title}}


def generate(seed: int = 20261110, per_profile: int = 6) -> dict:
    rng = random.Random(seed)
    personas = []
    i = 0
    for profile in P:
        for _ in range(per_profile):
            i += 1
            personas.append(make_persona(f"s{i:03d}", profile, rng))
    jds = []
    j = 0
    for role in P:
        if role in OUT_OF_CATALOG:
            continue
        for style in JD_STYLES:
            j += 1
            jds.append(make_jd(f"j{j:02d}", role, rng, style))
    return {"version": "synthetic-v2", "seed": seed, "as_of": AS_OF, "notice": NOTICE, "personas": personas, "jds": jds}


